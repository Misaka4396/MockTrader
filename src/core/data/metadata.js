/** code -> meta 索引 */
export const METADATA_BY_CODE = Object.fromEntries(METADATA.map((m) => [m.code, m]));

/** 按板块分组 */
export const BY_SECTOR = METADATA.reduce((acc, m) => {
  (acc[m.sector] = acc[m.sector] || []).push(m);
  return acc;
}, {});

export function getMeta(code) {
  return METADATA_BY_CODE[code];
}
